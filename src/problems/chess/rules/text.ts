/** the faces' width */
export const FW = 5;

/** pixel text centered at (cx, cy) in lit mirrors, in the live layout's face; scale 2 unless given */
export function drawText(v: Float32Array, text: string, cx: number, cy: number, scale?: number): Float32Array {
  const s = scale || 2, gap = s, cw = FW * s + gap, w = text.length * cw - gap, N = live.SIZE, FH = live.FH;
  let x = Math.round(cx - w / 2);
  const y0 = Math.round(cy - (FH * s) / 2), F = FH === 5 ? FONT5 : FONT;
  for (const ch of text.toUpperCase()) {
    const g = F[ch];
    if (g)
      for (let ry = 0; ry < FH; ry++)
        for (let rx = 0; rx < FW; rx++) {
          if (g[ry]![rx] !== "#") continue;
          for (let sy = 0; sy < s; sy++)
            for (let sx = 0; sx < s; sx++) {
              const px = x + rx * s + sx, py = y0 + ry * s + sy;
              if (px >= 0 && px < N && py >= 0 && py < N) v[py * N + px] = 1;
            }
        }
    x += cw;
  }
  return v;
}
