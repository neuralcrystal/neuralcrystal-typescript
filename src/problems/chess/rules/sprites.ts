// The piece art. Each sprite is drawn as rows of "#" (on) and "." (off): m = the silhouette, o = the outline (on the full set two
// mirrors thick with the art's interior lines; on the compact set the silhouette's rim), w = the pixels a white piece lights.
// A missing o is derived as the silhouette's rim; a missing w as the silhouette less the outline pixels that are not on the rim, so a
// white piece reads as a solid body with its inner lines dark.

/** a piece's art, every row a string of "#" and "." */
export interface Sprite {
  m: string[];
  o: string[];
  w: string[];
  /** the white art was drawn by hand rather than derived */
  wx?: boolean;
}

/** the six pieces by letter, P N B R Q K */
export type SpriteSet = Record<string, Sprite>;

type RawSprite = { m: string[]; o?: string[]; w?: string[]; wx?: boolean };

/** fill in each sprite's missing outline and white art (in place, so the key order stays m, o, w) */
function complete(set: Record<string, RawSprite>): SpriteSet {
  for (const k in set) {
    const S = set[k]!, n = S.m.length;
    const edge = (y: number, x: number): boolean =>
      [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dy, dx]) => {
        const Y = y + dy!, X = x + dx!;
        return Y < 0 || Y >= n || X < 0 || X >= n || S.m[Y]![X] !== "#";
      });
    // no outline given: the rim
    if (!S.o) S.o = S.m.map((row, y) => row.split("").map((c, x) => (c === "#" && edge(y, x) ? "#" : ".")).join(""));
    const o = S.o;
    // white: the silhouette less the inner lines (outline pixels off the rim), unless the sprite gives its own
    if (!S.w) S.w = S.m.map((row, y) => row.split("").map((c, x) => (c === "#" && !(o[y]![x] === "#" && !edge(y, x)) ? "#" : ".")).join(""));
  }
  return set as SpriteSet;
}

