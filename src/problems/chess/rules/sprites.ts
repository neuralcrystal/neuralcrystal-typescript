/**
 * A sprite pixel's mirror on a square; the piece keeps its color. A white piece on a dark square lights its silhouette with the inner
 * lines dark (w); on a light square only its outline goes dark. A black piece on a light square darkens its silhouette with the inner
 * lines lit (m less w); on a dark square only its outline lights. Returns 1 / 0 for a pixel of the piece, −1 outside it (the square
 * shows). The outline may run outside the silhouette: such a pixel is drawn in the outline renderings and left to the square in the
 * solid ones.
 */
export function spritePx(S: Sprite, solid: boolean, light: boolean, y: number, x: number): number {
  const m = S.m[y]![x] === "#", o = S.o[y]![x] === "#";
  if (!m && !o) return -1;
  if (solid) return light ? (o ? 0 : m ? 1 : -1) : m ? (S.w[y]![x] === "#" ? 1 : 0) : -1;
  return light ? (m ? (S.w[y]![x] === "#" ? 0 : 1) : -1) : o ? 1 : -1;
}
